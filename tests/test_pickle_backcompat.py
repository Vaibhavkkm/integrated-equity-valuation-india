"""
Phase A.0 — cache reload backward-compatibility tests.

Cached pickles created before the cash-flow fields were added must
deserialise successfully under the new dataclass schema, with the new
fields auto-defaulted to empty pd.Series. This is the same pattern used
when ``quarterly_earnings`` / ``quarterly_revenue`` were introduced.

These tests:
  1. Synthesise a *pre-extension* pickle by constructing a dict that
     mirrors the old field set and round-tripping through pickle. This
     simulates the on-disk format of caches created before Phase A.0
     without coupling the test to whatever pickles currently sit in
     ``cache/`` (those may be regenerated by other test runs).
  2. Load every real pickle in the project's ``cache/`` directory and
     assert each one deserialises and exposes the new fields as empty
     Series.  This is the integration check that protects users who
     have months of accumulated cache against a silent breakage.
"""
from __future__ import annotations

import pickle
import sys
from datetime import datetime, timezone
from pathlib import Path

import pandas as pd
import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.data_fetcher import CACHE_SCHEMA_VERSION, StockBundle, _load_from_cache


CACHE_DIR = Path(__file__).resolve().parents[1] / "cache"


def test_synthesised_pre_extension_pickle_loads_with_empty_new_fields(tmp_path):
    """Build a bundle without the new kwargs, pickle it, reload it,
    and confirm all six new fields default to empty Series.

    This is the dataclass-level guarantee: dataclasses with
    ``field(default_factory=...)`` populate missing fields on unpickle
    via __init__ defaults, so adding fields is non-breaking as long as
    the existing ones don't change position or name.
    """
    bundle = StockBundle(
        ticker="OLD.NS", sector="FMCG", name="Old Co",
        price=100.0, market_cap=1e10, shares_outstanding=1e8,
        beta_raw=1.0, price_history=pd.Series(dtype=float),
        eps_ttm=10.0, book_value_per_share=50.0, sales_per_share_ttm=80.0,
        dividend_per_share_ttm=5.0, free_cash_flow_per_share_ttm=8.0,
        revenue=8e9, ebitda=2e9, net_income=1e9,
        total_debt=5e8, cash=1e9, equity=4e9, total_assets=8e9,
        dividends_annual=pd.Series([4.5, 5.0]),
        earnings_annual=pd.Series([9.0, 10.0]),
        revenue_annual=pd.Series([7e9, 8e9]),
        book_value_annual=pd.Series([45.0, 50.0]),
        payout_ratio=0.5, roe=0.20, enterprise_value=1e10,
    )

    path = tmp_path / "OLD.NS.pkl"
    path.write_bytes(pickle.dumps(bundle))

    revived: StockBundle = pickle.loads(path.read_bytes())

    # Old fields intact
    assert revived.ticker == "OLD.NS"
    assert revived.eps_ttm == 10.0
    assert revived.payout_ratio == 0.5

    # New fields auto-defaulted to empty Series
    for name in (
        "net_income_annual", "capex_annual", "dep_amort_annual",
        "change_in_wc_annual", "working_capital_annual", "total_debt_annual",
    ):
        s = getattr(revived, name)
        assert isinstance(s, pd.Series), f"{name} not a Series after reload"
        assert s.empty, f"{name} should be empty for pre-extension pickle"


def _existing_cache_files() -> list[Path]:
    if not CACHE_DIR.exists():
        return []
    return sorted(CACHE_DIR.glob("*.pkl"))


@pytest.mark.skipif(
    not _existing_cache_files(),
    reason="No cached pickles present — nothing to back-compat test against.",
)
def test_all_existing_cache_pickles_deserialise():
    """Every pickle in the project's cache/ directory must load under
    the new schema. This is the integration test that protects users
    with accumulated local cache against a silent breakage on upgrade.
    """
    files = _existing_cache_files()
    assert files, "Expected at least one cache file"

    failures: list[str] = []
    for p in files:
        try:
            b: StockBundle = pickle.loads(p.read_bytes())
        except Exception as exc:
            failures.append(f"{p.name}: {exc.__class__.__name__}: {exc}")
            continue

        # Sanity: required new fields exist as Series
        for name in (
            "net_income_annual", "capex_annual", "dep_amort_annual",
            "change_in_wc_annual", "working_capital_annual", "total_debt_annual",
        ):
            attr = getattr(b, name, None)
            if not isinstance(attr, pd.Series):
                failures.append(
                    f"{p.name}: new field {name!r} is not a Series "
                    f"(got {type(attr).__name__})"
                )

    assert not failures, "Cache reload failures:\n  " + "\n  ".join(failures)


