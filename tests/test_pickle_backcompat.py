def test_setstate_migrates_pre_version_pickle_to_current_version(tmp_path):
    """A pickle whose __dict__ lacks _schema_version (or has a stale
    value) must be migrated up to CACHE_SCHEMA_VERSION via __setstate__.

    This is the operational guarantee that any code reading
    `bundle._schema_version` after a cache load sees the current
    version, never a stale one.
    """
    # Synthesise a v1-shaped __dict__ by constructing a bundle, then
    # mutating its dict to remove the _schema_version key entirely
    # (mimicking the on-disk shape of pre-Phase-A.0 pickles).
    bundle = StockBundle(
        ticker="V1.NS", sector="FMCG", name="V1 Co",
        price=100.0, market_cap=1e10, shares_outstanding=1e8,
        beta_raw=1.0, price_history=pd.Series(dtype=float),
        eps_ttm=10.0, book_value_per_share=50.0, sales_per_share_ttm=80.0,
        dividend_per_share_ttm=5.0, free_cash_flow_per_share_ttm=8.0,
        revenue=8e9, ebitda=2e9, net_income=1e9,
        total_debt=5e8, cash=1e9, equity=4e9, total_assets=8e9,
        dividends_annual=pd.Series(dtype=float),
        earnings_annual=pd.Series(dtype=float),
        revenue_annual=pd.Series(dtype=float),
        book_value_annual=pd.Series(dtype=float),
        payout_ratio=0.5, roe=0.20, enterprise_value=1e10,
    )
    state = bundle.__dict__.copy()
    # Drop the new field set + the schema version key — this is the
    # on-disk shape of a v1 pickle.
    for k in (
        "_schema_version",
        "net_income_annual", "capex_annual", "dep_amort_annual",
        "change_in_wc_annual", "working_capital_annual", "total_debt_annual",
    ):
        state.pop(k, None)
    raw_state = pickle.dumps((StockBundle, state))

    # Manually reconstruct via __setstate__ (the same path pickle.loads
    # exercises for a v1-shaped state dict).
    klass, restored_state = pickle.loads(raw_state)
    revived = klass.__new__(klass)
    revived.__setstate__(restored_state)

    assert revived._schema_version == CACHE_SCHEMA_VERSION
    # And every backfilled field is now a Series (not missing).
    for name in (
        "net_income_annual", "capex_annual", "dep_amort_annual",
        "change_in_wc_annual", "working_capital_annual", "total_debt_annual",
    ):
        assert isinstance(getattr(revived, name), pd.Series)
        assert getattr(revived, name).empty


@pytest.mark.skipif(
    not _existing_cache_files(),
    reason="No cached pickles present.",
)
def test_load_from_cache_helper_handles_pre_extension_pickles():
    """`_load_from_cache` is the public entry point for cache reads.
    It must succeed and return a StockBundle with the new fields, even
    when the on-disk pickle predates the field additions.
    """
    files = _existing_cache_files()
    sample = files[0]
    ticker = sample.stem  # e.g. "TCS.NS.pkl" → "TCS.NS"

    bundle = _load_from_cache(ticker, ttl=None)  # any-age, ignore TTL
    assert bundle is not None, f"Expected to load {ticker} from {sample}"
    # The six new fields must be present and well-typed.
    for name in (
        "net_income_annual", "capex_annual", "dep_amort_annual",
        "change_in_wc_annual", "working_capital_annual", "total_debt_annual",
    ):
        assert isinstance(getattr(bundle, name), pd.Series)
